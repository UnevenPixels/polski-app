export function getTopics() {
  return Object.entries(frequencyVocab).map(([id, topic]) => ({
    id,
    title: topic.title,
    titlePl: topic.titlePl,
    icon: topic.icon,
    count: topic.words.length
  }));
}

export function getTopic(id) {
  return frequencyVocab[id] || null;
}

export function getAllFrequencyWords() {
  const all = [];
  Object.entries(frequencyVocab).forEach(([topicId, topic]) => {
    topic.words.forEach(w => {
      all.push({ ...w, topic: topicId, topicTitle: topic.title });
    });
  });
  return all;
}
